def write_lut(lut: np.ndarray, dims: dict, constants: dict, varname: str, filename: str):
    """
    Write n-dimensional lookup table to NetCDF file

    :param lut: lookup table
    :param dims: dimensions
    :param filename: output filename
    :return:
    """
    if not isinstance(netCDF4, ModuleType):
        raise ModuleNotFoundError('write_netcdf requires the module netCDF4.')

    with netCDF4.Dataset(filename, 'w', format='NETCDF4') as d:
        # Global attributes
        d.title = f'Lookup Table of {varname} for case 1 waters generated by HydroLight6'
        d.description = 'Source code is the documentation.'
        d.conventions = 'CF-1.10,ACDD-1.3'
        d.id = f'he60_lut_{varname.lower()}_case1'
        d.naming_authority = 'HyperNavProjectOffice'
        d.source = 'HydroLight 6.0.1'
        d.date_created = f"{datetime.now().astimezone(timezone.utc).isoformat(timespec='seconds')}"
        d.product_version = __version__
        d.varname = varname

        # Constants
        for k, v in constants.items():
            dtype, fill_value = get_dtype(v)
            var = d.createVariable(k, dtype, fill_value=fill_value)
            var[...] = v

        # Dimensions
        for k, v in dims.items():
            d.createDimension(k, len(v))
            dtype, fill_value = get_dtype(v)
            var = d.createVariable(k, dtype, (k,), fill_value=fill_value)
            var[:] = v

        # LUT
        fill_value = np.nan if np.issubdtype(lut.dtype, np.floating) else None
        var = d.createVariable(varname, lut.dtype, tuple(dims.keys()), fill_value=fill_value)
        var[:] = lut


def read_lut(filename: str):
    """
    Read n-dimensional lookup table from NetCDF file

    :param filename: input filename
    :return: lut, dims, constants
    """
    if not isinstance(netCDF4, ModuleType):
        raise ModuleNotFoundError('read_netcdf requires the module netCDF4.')

    with netCDF4.Dataset(filename, 'r') as d:
        d.set_auto_mask(False)
        varname = d.varname
        # Constants
        constants = {}
        for k in d.variables.keys():
            if k == varname or k in d.dimensions:
                continue
            constants[k] = np.asarray(d.variables[k][:]).item()
            if d.variables[k].dtype == 'u1':
                constants[k] = bool(constants[k])
        # Dimensions
        dims = {}
        for dim_name in d.dimensions.keys():
            dims[dim_name] = d.variables[dim_name][:]
        # LUT
        lut = d.variables[varname][:]

    return lut, dims, constants
